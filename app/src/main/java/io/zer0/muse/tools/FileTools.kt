    /**
     * 执行工具调用。
     *
     * @param context 应用上下文(读取 filesDir/Download)
     * @param workspaceRoot 工作区根目录(用于解析工作区相对路径)
     */
    suspend fun execute(name: String, args: Map<String, String>, context: Context, workspaceRoot: File): String =
        withContext(Dispatchers.IO) {
            when (name) {
                NAME_READ_FILE -> execReadFile(args, context, workspaceRoot)
                NAME_CREATE_DOWNLOAD -> execCreateDownload(args, context)
                NAME_PARSE_LINK -> execParseLink(args, context)
                else -> "Error: unknown tool: $name"
            }
        }

    // ============================ read_file ============================

    private fun execReadFile(args: Map<String, String>, context: Context, workspaceRoot: File): String {
        val path = args["path"]?.takeIf { it.isNotBlank() }
            ?: return "Error: missing required parameter path"

        // 安全:禁止 .. 越权
        if (path.contains("..")) return "Error: path must not contain '..'"

        // 审计修复 (1.2): 拒绝绝对路径 — File(workspaceRoot, absolutePath) 会直接返回
        // 绝对路径本身(Java 忽略 parent),绕开下方候选目录白名单,可读应用私有任意文件。
        val rawPath = path.trim()
        // 工具输出回执用的是挂载形式 `tool_outputs:/x.txt`,这里按相对形式同一口处理
        val trimmedPath = if (rawPath.startsWith("$TOOL_OUTPUTS_DIR:/")) {
            TOOL_OUTPUTS_DIR + "/" + rawPath.removePrefix("$TOOL_OUTPUTS_DIR:/")
        } else {
            rawPath
        }
        val isAbsolute = trimmedPath.startsWith("/") || trimmedPath.startsWith("\\") ||
            Regex("^[A-Za-z]:[/\\\\]").containsMatchIn(trimmedPath)
        if (isAbsolute) {
            return "Error: absolute paths are not supported; use a workspace/private-directory relative path: $path"
        }

        // 解析候选路径:工作区相对路径 → filesDir → cacheDir → 外部 Download
        //（工具输出目录就在 filesDir 下，`tool_outputs/x.txt` 由下一条候选命中；
        //  不再额外拼 `tool_outputs/$path`，那层拼接在路径已带前缀时会变成双前缀，永远撞不上）
        val candidates = listOf(
            File(workspaceRoot, trimmedPath),
            File(context.filesDir, trimmedPath),
            File(context.cacheDir, trimmedPath),
            File(android.os.Environment.getExternalStoragePublicDirectory(android.os.Environment.DIRECTORY_DOWNLOADS), trimmedPath),
        )

        val target = candidates.firstOrNull { it.exists() && it.isFile }
            ?: return "Error: file does not exist or is not a regular file: $path" +
                // 用 filesDir 那一支推目录：tool_outputs/ 就挂在它下面。
                siblingHint(File(context.filesDir, trimmedPath))

        if (!target.canRead()) return "Error: file is not readable: ${target.absolutePath}"

        val size = target.length()
        val requestedOffset = args["offset_chars"]?.toIntOrNull()?.coerceAtLeast(0)
        val requestedLength = args["length_chars"]?.toIntOrNull()?.coerceAtLeast(0)
        if (requestedOffset != null || requestedLength != null || size > READ_FILE_AUTO_PAGE_BYTES) {
            return ToolTextFilePager.readPage(
                file = target,
                path = trimmedPath,
                charset = Charsets.UTF_8,
                requestedOffset = requestedOffset ?: 0,
                requestedLength = requestedLength ?: TOOL_OUTPUT_READ_PAGE_CHARS,
            )
        }

        return runCatching { target.readText() }
            .onFailure { Logger.w("FileTools", "read_file read failed: ${it.message}", it) }
            .getOrElse { "Error: read failed: ${it.message}" }
    }

    // ============================ create_download ============================

    private fun execCreateDownload(args: Map<String, String>, context: Context): String {
        val filename = args["filename"]?.takeIf { it.isNotBlank() }
            ?: return "Error: missing required parameter filename"
        val content = args["content"] ?: return "Error: missing required parameter content"
        val subdir = args["subdir"]?.trim()?.trim('/') ?: ""

        if (content.toByteArray().size > CREATE_DOWNLOAD_MAX_BYTES) {
            return "Error: content too large; the limit is ${CREATE_DOWNLOAD_MAX_BYTES / 1024 / 1024}MB"
        }

        // sanitize 文件名:仅保留字母数字下划线点连字符
        val safeFilename = filename.replace(Regex("[^A-Za-z0-9._-]"), "_")
            .takeIf { it.isNotBlank() } ?: "download_${System.currentTimeMillis()}.txt"

        // C-27: subdir 过滤 ".."/"." 段,防止逃逸 Download 目录
        val safeSubdir = subdir.split("/")
            .filter { it.isNotBlank() && it != ".." && it != "." }
            .joinToString("/")

        return runCatching {
            if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.Q) {
                // B-06: API 29+ scoped storage 直写公共目录必失败(EACCES),
                // 改走 MediaStore.Downloads(自动加入系统下载列表,重名自动加序号)。
                val resolver = context.contentResolver
                val relativePath = if (safeSubdir.isNotBlank()) {
                    "${android.os.Environment.DIRECTORY_DOWNLOADS}/$safeSubdir"
                } else {
                    android.os.Environment.DIRECTORY_DOWNLOADS
                }
                val values = android.content.ContentValues().apply {
                    put(android.provider.MediaStore.MediaColumns.DISPLAY_NAME, safeFilename)
                    put(android.provider.MediaStore.MediaColumns.MIME_TYPE, "text/plain")
                    put(android.provider.MediaStore.MediaColumns.RELATIVE_PATH, relativePath)
                }
                val uri = resolver.insert(android.provider.MediaStore.Downloads.EXTERNAL_CONTENT_URI, values)
                    ?: return "Error: unable to create a file in the Download directory"
                resolver.openOutputStream(uri)?.use { it.write(content.toByteArray()) }
                    ?: return "Error: unable to open the output stream"
                Logger.i("FileTools", "create_download succeeded (MediaStore): $safeFilename (${content.length} chars)")
                "Success: file saved to the Download directory\nFilename: $safeFilename" +
                    (if (safeSubdir.isNotBlank()) "\nSubdirectory: $safeSubdir" else "") +
                    "\nSize: ${content.length} characters"
            } else {
                // Android 9 以下:直接写公共目录(需 WRITE_EXTERNAL_STORAGE)
                val hasWritePerm = androidx.core.content.ContextCompat.checkSelfPermission(
                    context, android.Manifest.permission.WRITE_EXTERNAL_STORAGE,
                ) == android.content.pm.PackageManager.PERMISSION_GRANTED
                if (!hasWritePerm) return "Error: missing write storage permission (WRITE_EXTERNAL_STORAGE)"
                val downloadDir = android.os.Environment.getExternalStoragePublicDirectory(android.os.Environment.DIRECTORY_DOWNLOADS)
                val targetDir = if (safeSubdir.isNotBlank()) File(downloadDir, safeSubdir) else downloadDir
                if (!targetDir.exists()) targetDir.mkdirs()
                // 同名文件自动追加序号
                var target = File(targetDir, safeFilename)
                var idx = 1
                val dotIdx = safeFilename.lastIndexOf('.')
                val baseName = if (dotIdx > 0) safeFilename.substring(0, dotIdx) else safeFilename
                val ext = if (dotIdx > 0) safeFilename.substring(dotIdx) else ""
                while (target.exists()) {
                    target = File(targetDir, "$baseName($idx)$ext")
                    idx++
                }
                target.writeText(content)
                Logger.i("FileTools", "create_download succeeded: ${target.absolutePath} (${content.length} chars)")
                "Success: file saved to the Download directory\nPath: ${target.absolutePath}\nSize: ${content.length} characters"
            }
        }.getOrElse {
            Logger.w("FileTools", "create_download failed: ${it.message}", it)
            "Error: write failed: ${it.message}"
        }
    }

    // ============================ parse_link ============================

    private fun execParseLink(args: Map<String, String>, context: Context): String {
        val urlStr = args["url"]?.takeIf { it.isNotBlank() }
            ?: return "Error: missing required parameter url"

        if (!URLUtil.isNetworkUrl(urlStr)) return "Error: only HTTP/HTTPS URLs are supported"
        if (!urlStr.startsWith("http://") && !urlStr.startsWith("https://")) {
            return "Error: URL must start with http:// or https://"
        }

        // G3: SSRF 防护收敛到 SsrfGuard — 拒绝回环/私网/链路本地/保留地址(含
        // IPv4-mapped IPv6 与 fc00::/7 ULA,解析失败时保守拒绝)。
        // 防止 parse_link 抓取本机/内网服务。
        if (SsrfGuard.isBlocked(urlStr)) {
            return "Error: the target address is a loopback/intranet/reserved address; fetch rejected"
        }

        return runCatching {
            // B-30: 手动跟跳转 — instanceFollowRedirects=true 时 302 可带向内网
            // (初始 host 校验通过后,重定向目标不再校验)。关闭自动跟随,
            // 每一跳都重新过 SsrfGuard.isBlocked,最多 MAX_REDIRECTS 次。
            var currentUrl = urlStr
            var redirects = 0
            var conn: HttpURLConnection? = null
            while (true) {
                // G3: 每跳 URL 整体过 SsrfGuard(含 scheme 校验)
                if (SsrfGuard.isBlocked(currentUrl)) {
                    return "Error: the target address is a loopback/intranet/reserved address; fetch rejected"
                }
                conn?.disconnect()
                val u = URL(currentUrl)
                conn = (u.openConnection() as HttpURLConnection).apply {
                    connectTimeout = PARSE_LINK_TIMEOUT_MS
                    readTimeout = PARSE_LINK_TIMEOUT_MS
                    requestMethod = "GET"
                    setRequestProperty("User-Agent", "Mozilla/5.0 (Linux; Android) Muse/1.0")
                    setRequestProperty("Accept", "text/html,application/xhtml+xml")
                    instanceFollowRedirects = false
                }
                val code = conn.responseCode
                if (code in 300..399) {
                    val location = conn.getHeaderField("Location") ?: return "Error: HTTP $code: redirect is missing Location"
                    redirects++
                    if (redirects > MAX_REDIRECTS) return "Error: redirect count exceeded the limit ($MAX_REDIRECTS); terminated"
                    // 相对 Location 按当前 URL 解析
                    currentUrl = URL(u, location).toExternalForm()
                    continue
                }
                break
            }
            val finalConn = conn ?: return "Error: fetch failed: connection not established"
            try {
                val code = finalConn.responseCode
                if (code !in 200..299) return "Error: HTTP $code: ${finalConn.responseMessage}"

                val contentType = finalConn.contentType ?: ""
                if (!contentType.contains("html", ignoreCase = true)) {
                    val captured = finalConn.inputStream.bufferedReader(Charsets.UTF_8).use { reader ->
                        captureTextStream(
                            reader = reader,
                            outputDirectory = File(context.filesDir, TOOL_OUTPUTS_DIR),
                            filePrefix = "parse_link",
                            previewLimitChars = 0,
                        )
                    }
                    return "[Non-HTML content: $contentType]\n\n${captured.reference}"
                }

                // Retain the complete response while only building a bounded DOM parse preview.
                val captured = finalConn.inputStream.bufferedReader(Charsets.UTF_8).use { reader ->
                    captureTextStream(
                        reader = reader,
                        outputDirectory = File(context.filesDir, TOOL_OUTPUTS_DIR),
                        filePrefix = "parse_link_html",
                        previewLimitChars = PARSE_LINK_PARSE_PREVIEW_CHARS,
                    )
                }
                finalConn.disconnect()

                val doc = Jsoup.parse(captured.preview, currentUrl)
                val title = doc.title().trim().ifBlank { "(No title)" }
                // Jsoup 自动移除 script/style,再选 article 或 body
                val article = doc.selectFirst("article") ?: doc.body()
                val text = article.text().replace(Regex("\\s{2,}"), "\n").trim()

                Logger.i("FileTools", "parse_link succeeded: $currentUrl (${text.length} chars)")
                buildString {
                    append("# ").append(title).append("\n\nSource: ").append(currentUrl).append("\n\n")
                    append(text)
                    if (captured.savedFile != null) {
                        if (captured.totalChars > PARSE_LINK_PARSE_PREVIEW_CHARS) {
                            append("\n\n[Parsing only covers the first $PARSE_LINK_PARSE_PREVIEW_CHARS characters; the full page source can be read in chunks]\n")
                        } else {
                            append("\n\n[The full page source can be read in chunks]\n")
                        }
                        append(captured.reference)
                    }
                }
            } finally {
                finalConn.disconnect()
            }
        }.getOrElse {
            Logger.w("FileTools", "parse_link failed: ${it.message}", it)
            "Error: fetch failed: ${it.message}"
        }
    }
}

/**
 * v1.0.47 P2: FileTools 注册器 — 把 read_file/create_download/parse_link 注册到 ToolRegistry。
 *
 * 依赖 ToolRegistry + WorkspaceManager(取 rootDir)+ Context。
 */
class FileToolsRegistrar(
    private val toolRegistry: ToolRegistry,
    private val context: Context,
    private val workspaceRoot: File,
) {
    init {
        registerAll()
    }

    fun registerAll() {
        FileTools.toolDefs().forEach { def ->
            toolRegistry.register(def) { args ->
                FileTools.execute(def.name, args, context, workspaceRoot)
            }
        }
    }
}

/**
 * 读取失败时给一句「这里实际有什么」。
 *
 * 此前只报「不存在或不是普通文件」，模型被指引去 `workspace_list` 列目录 ——
 * 但 `tool_outputs/` 挂在 filesDir 下，不在 workspace 根里，那个动作根本够不着。
 * 直接在同目录列几个真实文件名，比让模型去试一个不存在的动作有用。
 */
private fun siblingHint(target: File): String {
    val dir = target.parentFile ?: return ""
    val names = runCatching {
        dir.listFiles()?.filter { it.isFile }?.take(5)?.map { it.name }
    }.getOrNull().orEmpty()
    if (names.isEmpty()) return ""
    return ". Existing in that directory: " + names.joinToString(", ")
}
